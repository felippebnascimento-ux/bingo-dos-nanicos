export const temIconePixel = (id: string) => id in ARTE;

/** O ícone em pixel art do item (vitrine, Mochila, efeito), ou null se ele não tem. */
export const IconePixel = memo(function IconePixel({ id }: { id: string }) {
  const arte = ARTE[id];
  if (!arte) return null;
  const px: { x: number; y: number; c: string }[] = [];
  arte.forEach((linha, y) => [...linha].forEach((c, x) => c !== "." && px.push({ x, y, c })));
  /* recorta num quadrado em volta do desenho (com 1 de folga), para o ícone ocupar o cartão inteiro */
  const xs = px.map((p) => p.x), ys = px.map((p) => p.y);
  const x0 = Math.min(...xs), x1 = Math.max(...xs) + 1, y0 = Math.min(...ys), y1 = Math.max(...ys) + 1;
  const lado = Math.max(x1 - x0, y1 - y0, 10) + 2;
  const vx = (x0 + x1) / 2 - lado / 2, vy = (y0 + y1) / 2 - lado / 2;
  return (
    <svg className="icone-pixel" viewBox={`${vx} ${vy} ${lado} ${lado}`} shapeRendering="crispEdges" aria-hidden="true">
      {px.map((p) => (
        <rect key={p.x + "," + p.y} x={p.x} y={p.y} width="1.02" height="1.02" className={"px-" + p.c} />
      ))}
    </svg>
  );
});
